// 4. Process all other app_*.arb files
const langFiles = fs.readdirSync(arbDir).filter(f => f.startsWith('app_') && f.endsWith('.arb') && f !== 'app_en.arb');

for (const file of langFiles) {
  const lang = file.replace('app_', '').replace('.arb', '');
  const filePath = path.join(arbDir, file);
  const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  const langTrans = translations[lang] || translations.en;
  for (const [key, val] of Object.entries(langTrans)) {
    content[key] = val;
  }

  fs.writeFileSync(filePath, JSON.stringify(content, null, 2) + '\n', 'utf8');
  console.log(`Updated ${file} with Batch 3 keys`);
}

