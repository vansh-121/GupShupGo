for (const [locale, filePath] of Object.entries(files)) {
  const fullPath = path.resolve(filePath);
  const content = fs.readFileSync(fullPath, 'utf8');
  const json = JSON.parse(content);

  const trans = allTranslations[locale];
  if (!trans) {
    console.error(`Missing translations for ${locale}`);
    continue;
  }

  // If English, add both key and @metadata
  if (locale === 'en') {
    for (const key of commonKeys) {
      json[key] = trans[key];
      json[`@${key}`] = enMetadata[key];
    }
  } else {
    for (const key of commonKeys) {
      json[key] = trans[key];
    }
  }

  fs.writeFileSync(fullPath, JSON.stringify(json, null, 2) + '\n', 'utf8');
  console.log(`Updated ${filePath}`);
}

